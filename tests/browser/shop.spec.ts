test('henna placement, resize, duplicate, undo, keyboard edit, persistence, and custom cart item', async ({ page }) => {
  await page.goto('/#henna')
  await page.getByRole('button', { name: 'Heart', exact: true }).click()
  const strip = page.locator('.henna-canvas')
  await strip.click({ position: { x: 160, y: 70 } })
  await expect(strip.locator('[data-motif-id]')).toHaveCount(1)
  await page.getByRole('slider', { name: /Motif size/ }).focus()
  await page.keyboard.press('End')
  await page.getByRole('button', { name: 'Duplicate', exact: true }).click()
  await expect(strip.locator('[data-motif-id]')).toHaveCount(2)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(strip.locator('[data-motif-id]')).toHaveCount(1)
  await strip.locator('[data-motif-id]').click()
  const before = await strip.locator('[data-motif-id]').getAttribute('transform')
  await strip.focus(); await page.keyboard.press('ArrowRight')
  await expect(strip.locator('[data-motif-id]')).not.toHaveAttribute('transform', before!)
  await page.reload(); await expect(strip.locator('[data-motif-id]')).toHaveCount(1)
  await page.getByRole('button', { name: 'Add your design to bag', exact: true }).click()
  await page.goto('/#cart')
  await expect(page.locator('.cart-item')).toContainText('Your henna stencil')
  await expect(page.locator('.cart-thumbnail img')).toHaveAttribute('src', /^data:image\/svg/)
})
test('nine-second lithophane intro, skip, upload, light toggle, dimensions and private saved photo', async ({ page }) => {
  await page.goto('/#lithophane')
  const video = page.locator('video')
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.duration)).toBe(9)
  await page.getByRole('button', { name: 'Skip intro', exact: true }).click()
  const fixture = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 300; c.height = 400; const ctx = c.getContext('2d')!; const g = ctx.createLinearGradient(0, 0, 300, 400); g.addColorStop(0, '#111111'); g.addColorStop(1, '#ffffff'); ctx.fillStyle = g; ctx.fillRect(0, 0, 300, 400); return c.toDataURL().split(',')[1] })
  await page.locator('input[type=file]').setInputFiles({ name: 'memory.png', mimeType: 'image/png', buffer: Buffer.from(fixture, 'base64') })
  const canvas = page.locator('.photo-frame canvas')
  await expect(canvas).toBeVisible()
  await expect.poll(() => canvas.evaluate((c: HTMLCanvasElement) => c.width)).toBe(600)
  const lit = await canvas.evaluate((c: HTMLCanvasElement) => c.toDataURL())
  await page.getByRole('button', { name: 'Light off', exact: true }).click()
  await expect.poll(() => page.locator('.photo-frame canvas').evaluate((c: HTMLCanvasElement) => c.toDataURL())).not.toBe(lit)
  await page.getByRole('button', { name: /12 × 16 cm/ }).click()
  await page.getByRole('checkbox', { name: /Add an LED base/ }).check()
  await expect(page.locator('.studio-price')).toContainText('110')
  await page.getByRole('button', { name: 'Rectangle', exact: true }).click()
  await page.getByRole('button', { name: 'Add to bag', exact: true }).click()
  await page.goto('/#cart')
  await expect(page.locator('.cart-item')).toContainText('Your photo, in a new light')
  const bag = await page.evaluate(() => JSON.parse(localStorage.getItem('elike-bag')!))
  expect(bag[0].assetId).toMatch(/^[0-9a-f-]{36}$/)
  expect(bag[0].config.shape).toBe('rectangle')
  expect(bag[0].price).toBe(110)
  await page.goto('/#lithophane'); await page.getByRole('button', { name: 'Skip intro', exact: true }).click()
  await expect(page.locator('.photo-frame canvas')).toBeVisible()
})
