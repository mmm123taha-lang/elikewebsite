for (const width of [360, 390, 430, 768, 1024, 1440]) for (const language of ['en', 'ar']) {
  test(`all shop screens fit ${width}px in ${language}`, async ({ page }) => {
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width, height: 960 }); await page.goto('/#home')
    if (language === 'ar') await page.locator('.language-button').click()
    await expect(page.locator('html')).toHaveAttribute('dir', language === 'ar' ? 'rtl' : 'ltr')
    for (const route of ['home', 'store', 'henna', 'lithophane', 'cart', 'checkout', 'account', 'orders']) {
      await page.goto(`/#${route}`); await expect(page.locator('.loading-page')).toHaveCount(0)
      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
    }
    expect(errors).toEqual([])
  })
}
